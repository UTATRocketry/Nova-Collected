class ConsoleHandler(BaseHTTPRequestHandler):
    server_version = "NovaConsole/1.0"
    collector: StatusCollector
    read_only: bool
    log_dir: str
    known_services: set

    def log_message(self, fmt, *args):  # quieter than the default access log
        pass

    # -- responses --

    def _send(self, code: int, body: bytes, ctype: str) -> None:
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _json(self, code: int, payload: dict) -> None:
        self._send(code, json.dumps(payload).encode("utf-8"), "application/json")

    # -- routes --

    def do_GET(self):  # noqa: N802
        path, _, query = self.path.partition("?")
        params = dict(p.split("=", 1) for p in query.split("&") if "=" in p)

        if path in ("/", "/index.html"):
            page = PAGE.replace("__READ_ONLY__", "true" if self.read_only else "false")
            self._send(200, page.encode("utf-8"), "text/html; charset=utf-8")
        elif path == "/api/health":
            self._json(200, {"ok": True})
        elif path == "/api/status":
            self._json(200, self.collector.get(force=params.get("force") == "1"))
        elif path == "/api/logs":
            name = urllib.parse.unquote(params.get("service", ""))
            if name not in self.known_services:
                self._send(404, b"unknown service", "text/plain; charset=utf-8")
                return
            out = tail_log(os.path.join(self.log_dir, f"{name}.out.log"))
            err = tail_log(os.path.join(self.log_dir, f"{name}.err.log"))
            body = f"--- {name}.out.log ---\n{out}\n\n--- {name}.err.log ---\n{err}\n"
            self._send(200, body.encode("utf-8"), "text/plain; charset=utf-8")
        else:
            self._send(404, b"not found", "text/plain; charset=utf-8")

    def do_POST(self):  # noqa: N802
        if self.path != "/api/action":
            self._send(404, b"not found", "text/plain; charset=utf-8")
            return
        if self.read_only:
            self._json(403, {"ok": False, "message": "console is running read-only"})
            return

        try:
            length = int(self.headers.get("Content-Length", "0"))
            payload = json.loads(self.rfile.read(length) or b"{}")
        except (ValueError, TypeError):
            self._json(400, {"ok": False, "message": "bad request body"})
            return

        name = payload.get("service", "")
        action = payload.get("action", "")
        # Only services named in the generated config may be controlled — never
        # an arbitrary name off the wire.
        if name not in self.known_services:
            self._json(400, {"ok": False, "message": f"unknown service {name!r}"})
            return

        ok, message = control_service(name, action)
        self.collector.get(force=True)
        self._json(200 if ok else 500, {"ok": ok, "message": message})


def main() -> None:
    parser = argparse.ArgumentParser(description="Nova ground station status console")
    parser.add_argument("--config", default=r"C:\Nova\console.json",
                        help="JSON config generated by ops/Nova.ps1")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--bind", default="0.0.0.0",
                        help="Bind address. Use 127.0.0.1 to keep the console "
                             "local to this PC only.")
    parser.add_argument("--read-only", action="store_true",
                        help="Serve status without start/stop/restart controls")
    args = parser.parse_args()

    config = load_config(args.config)
    collector = StatusCollector(config)

    known = {s["service"] for s in config.get("services", []) if s.get("service")}
    broker_service = config.get("broker", {}).get("service")
    if broker_service:
        known.add(broker_service)

    ConsoleHandler.collector = collector
    ConsoleHandler.read_only = args.read_only
    ConsoleHandler.log_dir = config.get("logDir", r"C:\Nova\logs")
    ConsoleHandler.known_services = known

    server = ThreadingHTTPServer((args.bind, args.port), ConsoleHandler)
    server.daemon_threads = True
    print(f"[nova-console] serving on http://{args.bind}:{args.port} "
          f"({len(known)} services, read_only={args.read_only})")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
