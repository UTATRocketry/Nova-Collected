#!/usr/bin/env python3
"""
nova_console.py — standalone status and control page for the Nova ground station.

Deliberately isolated: standard library only, no dependency on the novaOps
backend, the broker, or any Nova package. Its entire job is to tell an operator
what is running when something is not, so it must be the one thing that always
comes up.

Reads its configuration from the JSON file generated by ops/Nova.ps1 (default
C:\\Nova\\console.json), so a repo update never invalidates it.

    python nova_console.py --config C:\\Nova\\console.json --port 8080

Then open http://localhost:8080 (or http://<server-ip>:8080 from the operator
laptop).

Security note: any client that can reach this port can start and stop services.
That is intentional for an isolated ground-station LAN. Do not expose this port
to a routed or public network. Pass --read-only to serve status without the
control buttons.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import re
import socket
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

# Windows: keep console windows from flashing when we shell out to sc.exe/ping.
_NO_WINDOW = 0x08000000 if platform.system() == "Windows" else 0

# Service states we surface. Anything sc.exe reports that is not RUNNING or
# STOPPED is a transition and gets shown verbatim so a stuck STOP_PENDING is
# visible rather than rounded to "stopped".
_STATE_RE = re.compile(r"STATE\s+:\s+\d+\s+(\S+)")

STATUS_CACHE_TTL_S = 1.0
PROBE_TIMEOUT_S = 2.5


# ── configuration ────────────────────────────────────────────────────────────


DEFAULT_CONFIG = {
    "broker": {"service": "mosquitto", "host": "127.0.0.1", "port": 1883},
    "hosts": {},
    "server": "127.0.0.1",
    "logDir": r"C:\Nova\logs",
    "uiUrls": {},
    "services": [],
}


def load_config(path: str) -> dict:
    if not path or not os.path.exists(path):
        print(f"[nova-console] config not found at {path!r}; running with defaults",
              file=sys.stderr)
        return dict(DEFAULT_CONFIG)
    with open(path, "r", encoding="utf-8-sig") as fh:
        cfg = json.load(fh)
    merged = dict(DEFAULT_CONFIG)
    merged.update(cfg)
    return merged


# ── probes ───────────────────────────────────────────────────────────────────


def query_service(name: str) -> str:
    """Return RUNNING / STOPPED / START_PENDING / NOT_INSTALLED / UNKNOWN."""
    if platform.system() != "Windows":
        return "UNSUPPORTED"
    try:
        proc = subprocess.run(
            ["sc.exe", "query", name],
            capture_output=True, text=True, timeout=PROBE_TIMEOUT_S,
            creationflags=_NO_WINDOW,
        )
    except (subprocess.TimeoutExpired, OSError):
        return "UNKNOWN"
    if proc.returncode != 0:
        # 1060 is "the specified service does not exist".
        return "NOT_INSTALLED"
    match = _STATE_RE.search(proc.stdout)
    return match.group(1) if match else "UNKNOWN"


def control_service(name: str, action: str) -> tuple[bool, str]:
    """start / stop / restart a service via sc.exe. Returns (ok, message)."""
    if platform.system() != "Windows":
        return False, "service control is Windows-only"
    if action not in ("start", "stop", "restart"):
        return False, f"unknown action {action!r}"

    steps = ["stop", "start"] if action == "restart" else [action]
    for step in steps:
        try:
            proc = subprocess.run(
                ["sc.exe", step, name],
                capture_output=True, text=True, timeout=30,
                creationflags=_NO_WINDOW,
            )
        except (subprocess.TimeoutExpired, OSError) as exc:
            return False, f"{step} failed: {exc}"

        if proc.returncode != 0:
            text = (proc.stdout + proc.stderr).strip()
            # Stopping something already stopped is not a failure when we are
            # on our way to starting it again.
            already = "1062" in text or "not been started" in text
            if step == "stop" and action == "restart" and already:
                continue
            return False, f"{step} failed: {text}"

        if step == "stop":
            _wait_for_state(name, "STOPPED", timeout=20)

    return True, f"{action} issued"


def _wait_for_state(name: str, target: str, timeout: float) -> bool:
    deadline = time.time() + timeout
    while time.time() < deadline:
        if query_service(name) == target:
            return True
        time.sleep(0.4)
    return False


def probe_http(url: str) -> dict:
    if not url:
        return {"state": "n/a", "detail": ""}
    started = time.time()
    try:
        with urllib.request.urlopen(url, timeout=PROBE_TIMEOUT_S) as resp:
            ms = int((time.time() - started) * 1000)
            ok = 200 <= resp.status < 400
            return {"state": "ok" if ok else "bad",
                    "detail": f"HTTP {resp.status} · {ms} ms"}
    except urllib.error.HTTPError as exc:
        return {"state": "bad", "detail": f"HTTP {exc.code}"}
    except Exception as exc:  # socket errors, timeouts, refused connections
        return {"state": "down", "detail": type(exc).__name__}


def probe_tcp(host: str, port: int) -> dict:
    started = time.time()
    try:
        with socket.create_connection((host, port), timeout=PROBE_TIMEOUT_S):
            ms = int((time.time() - started) * 1000)
            return {"state": "ok", "detail": f"{ms} ms"}
    except Exception as exc:
        return {"state": "down", "detail": type(exc).__name__}


def probe_ping(host: str) -> dict:
    """ICMP check. The Pis listen on no fixed TCP port, so ping is the honest
    liveness signal for the box itself (not for novaGround the process)."""
    if platform.system() == "Windows":
        cmd = ["ping", "-n", "1", "-w", "900", host]
    else:
        cmd = ["ping", "-c", "1", "-W", "1", host]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=4,
                              creationflags=_NO_WINDOW)
        if proc.returncode == 0:
            match = re.search(r"time[=<]\s*(\d+)\s*ms", proc.stdout)
            detail = f"{match.group(1)} ms" if match else "reply"
            return {"state": "ok", "detail": detail}
        return {"state": "down", "detail": "no reply"}
    except Exception as exc:
        return {"state": "down", "detail": type(exc).__name__}


def tail_log(path: str, lines: int = 80) -> str:
    if not path or not os.path.exists(path):
        return f"(no log at {path})"
    try:
        with open(path, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            size = fh.tell()
            block = min(size, 64 * 1024)
            fh.seek(size - block)
            data = fh.read().decode("utf-8", errors="replace")
        return "\n".join(data.splitlines()[-lines:])
    except OSError as exc:
        return f"(could not read log: {exc})"


# ── status assembly ──────────────────────────────────────────────────────────


class StatusCollector:
    """Collects the whole picture in parallel, with a short cache so a browser
    polling every second cannot pile up probes faster than they complete."""

    def __init__(self, config: dict):
        self.config = config
        self._lock = threading.Lock()
        self._cached: dict | None = None
        self._cached_at = 0.0
        self._pool = ThreadPoolExecutor(max_workers=12)

    def get(self, force: bool = False) -> dict:
        with self._lock:
            fresh = self._cached is not None and (time.time() - self._cached_at) < STATUS_CACHE_TTL_S
            if fresh and not force:
                return self._cached
        snapshot = self._collect()
        with self._lock:
            self._cached = snapshot
            self._cached_at = time.time()
        return snapshot

    def _collect(self) -> dict:
        cfg = self.config
        broker = cfg.get("broker", {})

        broker_svc = self._pool.submit(query_service, broker.get("service", "mosquitto"))
        broker_tcp = self._pool.submit(probe_tcp, broker.get("host", "127.0.0.1"),
                                       int(broker.get("port", 1883)))

        host_futures = {
            name: self._pool.submit(probe_ping, info.get("ip", ""))
            for name, info in cfg.get("hosts", {}).items()
        }

        svc_futures = []
        for svc in cfg.get("services", []):
            svc_futures.append((
                svc,
                self._pool.submit(query_service, svc["service"]),
                self._pool.submit(probe_http, svc.get("health") or ""),
            ))

        services = []
        for svc, state_f, health_f in svc_futures:
            state = state_f.result()
            health = health_f.result() if state == "RUNNING" else {"state": "n/a", "detail": ""}
            services.append({
                "component": svc.get("component"),
                "env": svc.get("env"),
                "service": svc.get("service"),
                "label": svc.get("label"),
                "state": state,
                "health": health,
                "overall": _overall(state, health),
            })

        return {
            "time": time.strftime("%H:%M:%S"),
            "broker": {
                "service": broker.get("service"),
                "state": broker_svc.result(),
                "port": broker_tcp.result(),
                "endpoint": f"{broker.get('host')}:{broker.get('port')}",
            },
            "hosts": [
                {
                    "name": name,
                    "ip": info.get("ip", ""),
                    "mdns": info.get("mdns", ""),
                    "ping": host_futures[name].result(),
                }
                for name, info in cfg.get("hosts", {}).items()
            ],
            "services": services,
            "uiUrls": cfg.get("uiUrls", {}),
            "server": cfg.get("server", ""),
        }


def _overall(state: str, health: dict) -> str:
    """green = running and answering, amber = running but not answering (or
    mid-transition), red = not running."""
    if state != "RUNNING":
        if state in ("START_PENDING", "STOP_PENDING"):
            return "amber"
        return "red"
    if health["state"] in ("ok", "n/a"):
        return "green"
    return "amber"


